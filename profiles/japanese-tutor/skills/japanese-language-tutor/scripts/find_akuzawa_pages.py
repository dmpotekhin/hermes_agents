def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    pdf = sys.argv[1]
    start = int(sys.argv[2]) if len(sys.argv) > 2 else 17  # паттерны N4 с стр. 18
    doc = fitz.open(pdf)
    pages_text = [doc[i].get_text() for i in range(doc.page_count)]
    cur = start
    for key, disp in TOC_N4:
        page = None
        for i in range(cur, doc.page_count):
            if key in pages_text[i].strip()[:150]:
                page = i + 1
                break
        if page is None:
            page = '?'
        else:
            cur = page - 1  # разрешить соседним записям тот же раздел
        print(f'{page}\t{disp}')


if __name__ == '__main__':
    main()
